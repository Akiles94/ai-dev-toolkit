import type { Agent } from "../core/agent.ts";

/** A file an adapter produces, relative to the repository root. */
export interface GeneratedFile {
  readonly path: string;
  readonly content: string;
}

/** Renders a canonical agent into the files one AI tool understands. */
export type Adapter = (agent: Agent, source: string) => GeneratedFile[];

/** YAML scalar that survives any character: a JSON string is a valid YAML double-quoted string. */
export const yamlString = (value: string): string => JSON.stringify(value);

/** Banner placed right after the frontmatter, where tools still read the file correctly. */
export const generatedBanner = (source: string): string =>
  `<!-- Generated by aidt sync from ${source}. Edit that file and run \`aidt sync\`. -->`;

/**
 * The agent's file and command limits written as instructions, for tools that cannot enforce them
 * as permissions. Empty when the agent has no scoped capability.
 */
export function limitsSection(agent: Agent): string {
  const lines: string[] = [];
  if (agent.writes.length > 0) {
    lines.push("Create or change only these files:", ...agent.writes.map((g) => `- \`${g}\``));
  }
  if (agent.commands.length > 0) {
    lines.push("Run only commands starting with:", ...agent.commands.map((c) => `- \`${c}\``));
  }
  if (!agent.capabilities.includes("edit")) lines.push("Never change source code.");
  return lines.length === 0 ? "" : ["## Limits", "", ...lines].join("\n");
}

/** Joins the parts of a generated Markdown file, skipping empty ones. */
export const markdown = (...parts: string[]): string =>
  `${parts.filter((part) => part !== "").join("\n\n")}\n`;
