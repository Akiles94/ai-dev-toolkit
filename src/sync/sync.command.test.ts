import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { featureRepo } from "../shared/testing/temp-repo.ts";
import { bannerSource, planSync, staleFiles, writeSync } from "./sync.command.ts";
import { REFINER } from "./testing/sample-agent.ts";

function repoWithAgents(files: Record<string, string>): string {
  const repo = featureRepo();
  mkdirSync(join(repo, ".aidt", "agents"), { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    writeFileSync(join(repo, ".aidt", "agents", name), content);
  }
  return repo;
}

describe("sync", () => {
  it("renders every agent for every harness and writes the files", async () => {
    const repo = repoWithAgents({ "refiner.md": REFINER, "README.md": "# not an agent" });
    const plan = await planSync(repo, ".aidt/agents", ["copilot"]);
    expect(plan.problems).toEqual([]);
    expect(plan.files.map((f) => f.path)).toEqual([".github/agents/refiner.agent.md"]);

    await writeSync(repo, plan);
    const written = readFileSync(join(repo, ".github", "agents", "refiner.agent.md"), "utf8");
    expect(written).toBe(plan.files[0]?.content);
  });

  it("reports invalid agents and unknown harnesses", async () => {
    const repo = repoWithAgents({ "refiner.md": REFINER, "broken.md": "no frontmatter" });
    const plan = await planSync(repo, ".aidt/agents", ["copilot", "notepad"]);
    expect(plan.problems.map((p) => p.file)).toEqual(["sync.harnesses", ".aidt/agents/broken.md"]);
  });
});

describe("sync with part of the workflow", () => {
  const PLANNER = REFINER.replace("name: refiner", "name: planner").replace(
    "handoff: planner\n",
    "",
  );

  it("offers the handoff only when the next agent is installed", async () => {
    const alone = await planSync(repoWithAgents({ "refiner.md": REFINER }), ".aidt/agents", [
      "copilot",
    ]);
    expect(alone.files[0]?.content.includes("handoffs:")).toBe(false);

    const both = repoWithAgents({ "refiner.md": REFINER, "planner.md": PLANNER });
    const chained = await planSync(both, ".aidt/agents", ["copilot"]);
    const refiner = chained.files.find((f) => f.path === ".github/agents/refiner.agent.md");
    expect(refiner?.content.includes("agent: planner")).toBe(true);
  });

  it("removes generated files whose agent was deleted, never hand-written ones", async () => {
    const repo = repoWithAgents({ "refiner.md": REFINER, "planner.md": PLANNER });
    await writeSync(repo, await planSync(repo, ".aidt/agents", ["copilot", "claude-code"]));
    writeFileSync(join(repo, ".github", "agents", "mine.agent.md"), "# written by hand\n");
    const planner = join(repo, ".aidt", "agents", "planner.md");
    rmSync(planner);

    const plan = await planSync(repo, ".aidt/agents", ["copilot", "claude-code"]);
    expect(plan.orphans).toEqual([
      ".claude/skills/planner/SKILL.md",
      ".github/agents/planner.agent.md",
    ]);
    // The refiner loses its handoff to the planner, so its files change too.
    expect(await staleFiles(repo, plan.files)).toEqual([
      ".github/agents/refiner.agent.md",
      ".claude/skills/refiner/SKILL.md",
    ]);

    await writeSync(repo, plan);
    expect(existsSync(join(repo, ".github", "agents", "planner.agent.md"))).toBe(false);
    expect(existsSync(join(repo, ".github", "agents", "mine.agent.md"))).toBe(true);
  });
});

describe("sync only removes what it generated", () => {
  it("reads the source agent from the banner right after the frontmatter, nowhere else", () => {
    const banner = "<!-- Generated by aidt sync from .aidt/agents/planner.md. Edit that file. -->";
    expect(bannerSource(`---\nname: planner\n---\n\n${banner}\n\nBody\n`)).toBe(
      ".aidt/agents/planner.md",
    );
    expect(bannerSource(`# Notes\n\nOur generated files start with:\n\n${banner}\n`)).toBe(
      undefined,
    );
    expect(bannerSource(`---\nname: mine\n---\n\nWritten by hand.\n\n${banner}\n`)).toBe(undefined);
  });

  it("with --from another folder, leaves the files of the usual agents alone", async () => {
    const repo = repoWithAgents({ "refiner.md": REFINER });
    await writeSync(repo, await planSync(repo, ".aidt/agents", ["copilot"]));
    mkdirSync(join(repo, "drafts"));
    writeFileSync(
      join(repo, "drafts", "planner.md"),
      REFINER.replace("name: refiner", "name: planner"),
    );

    const plan = await planSync(repo, "drafts", ["copilot"]);
    expect(plan.orphans).toEqual([]);
  });
});

describe("sync --check", () => {
  it("lists generated files that are missing or edited by hand", async () => {
    const repo = featureRepo();
    mkdirSync(join(repo, ".aidt", "agents"), { recursive: true });
    writeFileSync(join(repo, ".aidt", "agents", "refiner.md"), REFINER);
    const plan = await planSync(repo, ".aidt/agents", ["copilot", "claude-code"]);
    expect(await staleFiles(repo, plan.files)).toEqual([
      ".github/agents/refiner.agent.md",
      ".claude/skills/refiner/SKILL.md",
    ]);

    await writeSync(repo, plan);
    expect(await staleFiles(repo, plan.files)).toEqual([]);

    writeFileSync(join(repo, ".claude", "skills", "refiner", "SKILL.md"), "edited by hand");
    expect(await staleFiles(repo, plan.files)).toEqual([".claude/skills/refiner/SKILL.md"]);
  });
});
