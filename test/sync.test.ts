import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { allowedTools, claudeCode } from "../src/adapters/claude-code.ts";
import { copilot } from "../src/adapters/copilot.ts";
import { planSync, staleFiles, writeSync } from "../src/commands/sync.ts";
import { type Agent, parseAgent } from "../src/core/agent.ts";
import { featureRepo } from "./helpers/repo.ts";

const REFINER = `---
name: refiner
description: Turns a ticket into a business spec before any code.
tier: balanced
capabilities: [read, ask, write, shell]
writes:
  - .aidt/tasks/*/spec.md
commands:
  - git branch
handoff: planner
---
Ask business questions only.
`;

function parsed(file: string, markdown: string): Agent {
  const result = parseAgent(file, markdown);
  if (!result.ok) throw new Error(result.error.join("; "));
  return result.value;
}

describe("parseAgent", () => {
  it("reads a valid agent", () => {
    const agent = parsed("refiner.md", REFINER);
    expect(agent.capabilities).toEqual(["read", "ask", "write", "shell"]);
    expect(agent.writes).toEqual([".aidt/tasks/*/spec.md"]);
    expect(agent.handoff).toBe("planner");
    expect(agent.instructions).toBe("Ask business questions only.");
  });

  it("reports every problem at once", () => {
    const broken = "---\nname: other\ntier: huge\ncapabilities: [read, fly, write]\n---\nBody\n";
    const result = parseAgent("refiner.md", broken);
    expect(result.ok ? [] : result.error).toEqual([
      'name "other" must match the file name',
      "description is missing or too short",
      "tier must be one of efficient, balanced, max",
      'unknown capability "fly"',
      "the write capability needs a writes list",
    ]);
  });

  it("accepts Windows line endings", () => {
    expect(parseAgent("refiner.md", REFINER.replace(/\n/g, "\r\n")).ok).toBe(true);
  });

  it("rejects a file without frontmatter", () => {
    expect(parseAgent("refiner.md", "Just text").ok).toBe(false);
  });
});

describe("copilot adapter", () => {
  const [file] = copilot(parsed("refiner.md", REFINER), ".aidt/agents/refiner.md");
  const content = file?.content ?? "";

  it("writes a VS Code custom agent", () => {
    expect(file?.path).toBe(".github/agents/refiner.agent.md");
    expect(content.startsWith("---\nname: refiner\n")).toBe(true);
  });

  it("maps capabilities to Copilot tools", () => {
    expect(content).toContain(
      'tools: ["read", "search", "vscode/askQuestions", "edit", "execute/runInTerminal", "execute/getTerminalOutput"]',
    );
  });

  it("offers the handoff without sending it", () => {
    expect(content).toContain('  - label: "Continue with planner"\n    agent: planner');
    expect(content).toContain("    send: false");
  });

  it("states the limits Copilot cannot enforce, then the instructions", () => {
    expect(content).toContain("Create or change only these files:\n- `.aidt/tasks/*/spec.md`");
    expect(content).toContain("Run only commands starting with:\n- `git branch`");
    expect(content).toContain("Never change source code.");
    expect(content.trimEnd().endsWith("Ask business questions only.")).toBe(true);
  });

  it("marks the file as generated", () => {
    expect(content).toContain("Generated by aidt sync from .aidt/agents/refiner.md");
  });
});

describe("sync", () => {
  function repoWithAgents(files: Record<string, string>): string {
    const repo = featureRepo();
    mkdirSync(join(repo, ".aidt", "agents"), { recursive: true });
    for (const [name, content] of Object.entries(files)) {
      writeFileSync(join(repo, ".aidt", "agents", name), content);
    }
    return repo;
  }

  it("renders every agent for every harness and writes the files", async () => {
    const repo = repoWithAgents({ "refiner.md": REFINER, "README.md": "# not an agent" });
    const plan = await planSync(repo, ".aidt/agents", ["copilot"]);
    expect(plan.problems).toEqual([]);
    expect(plan.files.map((f) => f.path)).toEqual([".github/agents/refiner.agent.md"]);

    await writeSync(repo, plan.files);
    const written = readFileSync(join(repo, ".github", "agents", "refiner.agent.md"), "utf8");
    expect(written).toBe(plan.files[0]?.content);
  });

  it("reports invalid agents and unknown harnesses", async () => {
    const repo = repoWithAgents({ "refiner.md": REFINER, "broken.md": "no frontmatter" });
    const plan = await planSync(repo, ".aidt/agents", ["copilot", "notepad"]);
    expect(plan.problems.map((p) => p.file)).toEqual(["sync.harnesses", ".aidt/agents/broken.md"]);
  });
});

describe("claude code adapter", () => {
  const skill = (markdown: string, file = "refiner.md") =>
    claudeCode(parsed(file, markdown), `.aidt/agents/${file}`)[0];

  it("writes a skill the user invokes as a slash command", () => {
    const file = skill(REFINER);
    expect(file?.path).toBe(".claude/skills/refiner/SKILL.md");
    expect(file?.content).toContain("disable-model-invocation: true");
    expect(file?.content).toContain("model: sonnet");
  });

  it("pre-approves only the scoped writes and commands", () => {
    expect(allowedTools(parsed("refiner.md", REFINER))).toEqual([
      "Read",
      "Grep",
      "Glob",
      "AskUserQuestion",
      "Edit(.aidt/tasks/*/spec.md)",
      "Bash(git branch *)",
    ]);
  });

  it("suggests the next step instead of starting it", () => {
    expect(skill(REFINER)?.content.trimEnd().endsWith("Never start it yourself.")).toBe(true);
  });

  it("runs a fresh-context agent in a forked subagent that waits for the result", () => {
    const content = skill(
      REFINER.replace("tier: balanced", "tier: efficient\ncontext: fresh"),
    )?.content;
    expect(content).toContain("model: haiku");
    expect(content).toContain("context: fork\nagent: general-purpose\nbackground: false");
    expect(content).toContain("## Running in a fresh context");
  });

  it("rejects an unknown context", () => {
    const result = parseAgent("refiner.md", REFINER.replace("tier:", "context: shy\ntier:"));
    expect(result.ok ? [] : result.error).toEqual(["context must be one of shared, fresh"]);
  });
});

describe("sync --check", () => {
  it("lists generated files that are missing or edited by hand", async () => {
    const repo = featureRepo();
    mkdirSync(join(repo, ".aidt", "agents"), { recursive: true });
    writeFileSync(join(repo, ".aidt", "agents", "refiner.md"), REFINER);
    const plan = await planSync(repo, ".aidt/agents", ["copilot", "claude-code"]);
    expect(await staleFiles(repo, plan.files)).toEqual([
      ".github/agents/refiner.agent.md",
      ".claude/skills/refiner/SKILL.md",
    ]);

    await writeSync(repo, plan.files);
    expect(await staleFiles(repo, plan.files)).toEqual([]);

    writeFileSync(join(repo, ".claude", "skills", "refiner", "SKILL.md"), "edited by hand");
    expect(await staleFiles(repo, plan.files)).toEqual([".claude/skills/refiner/SKILL.md"]);
  });
});
